#!/usr/bin/env python3
"""Generate Sources/Redlight/ZoneCoordinates.swift from the tz database.

Adaptive falls back to the city of the Mac's time zone when it has no location fix.
`zone.tab` gives every zone's principal city; `tzdata.zi` gives the old names that are
links to those zones. Run this after a tz database update:

    python3 Tools/generate-zone-coordinates.py
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ZONEINFO = Path("/usr/share/zoneinfo")
OUTPUT = ROOT / "Sources" / "Redlight" / "ZoneCoordinates.swift"

_COORDINATES = re.compile(r"^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$")


def parse_coordinates(text: str) -> tuple[float, float]:
    """ISO 6709 `±DDMM±DDDMM` or `±DDMMSS±DDDMMSS` to decimal degrees."""
    match = _COORDINATES.match(text)
    if not match:
        raise ValueError(f"not ISO 6709 coordinates: {text!r}")
    lat_sign, lat_d, lat_m, lat_s, lon_sign, lon_d, lon_m, lon_s = match.groups()

    def degrees(sign: str, d: str, m: str, s: str | None) -> float:
        value = int(d) + int(m) / 60 + int(s or 0) / 3600
        return -value if sign == "-" else value

    return degrees(lat_sign, lat_d, lat_m, lat_s), degrees(lon_sign, lon_d, lon_m, lon_s)


def parse_zone_tab(text: str) -> dict[str, tuple[float, float]]:
    """Zone name to (latitude, longitude). The first row for a zone wins."""
    zones: dict[str, tuple[float, float]] = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 3:
            continue
        zones.setdefault(fields[2], parse_coordinates(fields[1]))
    return zones


def parse_links(text: str, zones: dict[str, tuple[float, float]]) -> dict[str, str]:
    """Link name to the zone in `zones` it resolves to. Names already in `zones` are skipped."""
    targets: dict[str, str] = {}
    for line in text.splitlines():
        fields = line.split()
        if len(fields) >= 3 and fields[0] == "L":
            targets[fields[2]] = fields[1]
    links: dict[str, str] = {}
    for name in targets:
        if name in zones:
            continue
        target, seen = targets[name], {name}
        while target not in zones and target in targets and target not in seen:
            seen.add(target)
            target = targets[target]
        if target in zones:
            links[name] = target
    return links


def number(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def render(zones: dict[str, tuple[float, float]], links: dict[str, str], version: str) -> str:
    rows = "\n".join(f"    {name} {number(lat)} {number(lon)}" for name, (lat, lon) in sorted(zones.items()))
    link_rows = "\n".join(f"    {name} {target}" for name, target in sorted(links.items()))
    return f'''// Generated by Tools/generate-zone-coordinates.py from the tz database {version}
// (zone.tab and tzdata.zi). Do not edit: run the script again instead.

/// Every tz database zone's principal city, and the old zone names that link to them.
/// `ApproximateLocation` reads these when Adaptive has no location fix.
enum ZoneCoordinates {{
    /// Zone name to its city's latitude and longitude in degrees.
    static let table: [String: (latitude: Double, longitude: Double)] = {{
        var table: [String: (latitude: Double, longitude: Double)] = [:]
        for row in zones.split(separator: "\\n") {{
            let fields = row.split(separator: " ")
            guard fields.count == 3, let latitude = Double(fields[1]), let longitude = Double(fields[2])
            else {{ continue }}
            table[String(fields[0])] = (latitude, longitude)
        }}
        return table
    }}()

    /// Old or alternative zone name to the zone in `table` it is a link to.
    static let aliases: [String: String] = {{
        var aliases: [String: String] = [:]
        for row in links.split(separator: "\\n") {{
            let fields = row.split(separator: " ")
            guard fields.count == 2 else {{ continue }}
            aliases[String(fields[0])] = String(fields[1])
        }}
        return aliases
    }}()

    static let zoneCount = {len(zones)}
    static let aliasCount = {len(links)}

    private static let zones = """
{rows}
    """

    private static let links = """
{link_rows}
    """
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--zoneinfo", type=Path, default=DEFAULT_ZONEINFO,
                        help="directory holding zone.tab, tzdata.zi and +VERSION")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    zones = parse_zone_tab((args.zoneinfo / "zone.tab").read_text(encoding="utf-8"))
    links = parse_links((args.zoneinfo / "tzdata.zi").read_text(encoding="utf-8"), zones)
    version_file = args.zoneinfo / "+VERSION"
    version = version_file.read_text(encoding="utf-8").strip() if version_file.exists() else "(unknown version)"
    args.output.write_text(render(zones, links, version), encoding="utf-8")
    print(f"{args.output}: {len(zones)} zones, {len(links)} links, tz database {version}")


if __name__ == "__main__":
    main()
